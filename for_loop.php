
<?php
// For Loop Example

// $i = 1 : Start from 1
// $i <= 5 : Continue while i is less than or equal to 5
// $i++ : Increase i by 1 after each loop

for ($i = 1; $i <= 5; $i++) {

    // Display current number
    echo "Number: " . $i . "<br>";
}
?>

